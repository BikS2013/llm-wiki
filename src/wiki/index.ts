import fs from 'node:fs';
import path from 'node:path';
import { asStringList, withFrontmatter, type Frontmatter } from './markdown.js';
import { LinkResolver, listPages, type Page, type PageType, type WikiPaths } from './layout.js';
import { WIKI_CSS } from './format.js';

const GROUPS: Array<{ type: PageType; heading: string }> = [
  { type: 'overview', heading: 'Overview' },
  { type: 'entity', heading: 'Entities' },
  { type: 'concept', heading: 'Concepts' },
  { type: 'synthesis', heading: 'Syntheses & answers' },
  { type: 'source', heading: 'Sources' },
  { type: 'lint', heading: 'Lint reports' },
  { type: 'other', heading: 'Other pages' },
];

function summaryOf(fm: Frontmatter, text: string): string {
  if (typeof fm.summary === 'string' && fm.summary.trim() !== '') return fm.summary.trim();
  const para = text
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .find((p) => p !== '' && !p.startsWith('#') && !p.startsWith('```') && !p.startsWith('|'));
  if (!para) return '';
  const oneLine = para.replace(/\s+/g, ' ');
  return oneLine.length > 160 ? `${oneLine.slice(0, 157)}…` : oneLine;
}

function metaOf(fm: Frontmatter): string {
  const bits: string[] = [];
  const updated = fm.updated ?? fm.created ?? fm.date;
  if (typeof updated === 'string' && updated !== '') bits.push(updated);
  const sources = asStringList(fm.sources);
  if (sources.length > 0) bits.push(`${sources.length} source${sources.length === 1 ? '' : 's'}`);
  return bits.length > 0 ? ` _(${bits.join(', ')})_` : '';
}

/** The index as frontmatter + markdown body (with `[[wikilinks]]`), generated from page frontmatter and bodies. */
export function indexParts(pages: Page[]): { frontmatter: Frontmatter; body: string } {
  const resolver = new LinkResolver(pages);
  const lines: string[] = [
    '# Index',
    '',
    'Catalog of every page in the wiki, grouped by type. Generated by `llm-wiki index`; do not edit by hand — edit page frontmatter (`title`, `summary`, `type`, `updated`, `sources`) instead.',
    '',
  ];
  for (const group of GROUPS) {
    const members = pages.filter((p) => p.type === group.type);
    if (members.length === 0) continue;
    lines.push(`## ${group.heading} (${members.length})`, '');
    for (const p of members.sort((a, b) => a.title.localeCompare(b.title))) {
      const summary = summaryOf(p.frontmatter, p.text);
      lines.push(`- [[${resolver.shortLink(p)}|${p.title}]]${summary ? ` — ${summary}` : ''}${metaOf(p.frontmatter)}`);
    }
    lines.push('');
  }
  if (pages.length === 0) lines.push('_The wiki is empty. Ingest a source with `llm-wiki ingest <file>`._', '');
  return { frontmatter: { title: 'Index', type: 'index', pages: pages.length }, body: lines.join('\n') };
}

/** Renders the index in markdown (the form `index.md` takes, and the form shown to the LLM). */
export function renderIndex(pages: Page[]): string {
  const { frontmatter, body } = indexParts(pages);
  return withFrontmatter(frontmatter, body);
}

/** Renders the index file in the wiki's format (`index.md` or `index.html`). */
export function renderIndexFile(paths: WikiPaths, pages: Page[]): string {
  if (paths.format.name === 'markdown') return renderIndex(pages);
  const { frontmatter, body } = indexParts(pages);
  const resolver = new LinkResolver(pages);
  const html = paths.format.prepare(body, 'index', (t) => resolver.resolve(t)?.id);
  return paths.format.render(frontmatter, html, 'index');
}

/** HTML wikis share one stylesheet, `wiki/wiki.css`; created when missing, never overwritten. */
export function ensureStylesheet(paths: WikiPaths): string | undefined {
  if (paths.format.name !== 'html') return undefined;
  const css = path.join(paths.wiki, 'wiki.css');
  if (fs.existsSync(css)) return undefined;
  fs.writeFileSync(css, WIKI_CSS);
  return css;
}

/** Regenerates the index file; returns true when its content changed. */
export function writeIndex(paths: WikiPaths, pages = listPages(paths)): boolean {
  ensureStylesheet(paths);
  const next = renderIndexFile(paths, pages);
  const prev = fs.existsSync(paths.index) ? fs.readFileSync(paths.index, 'utf8') : undefined;
  if (prev === next) return false;
  fs.writeFileSync(paths.index, next);
  return true;
}

export function indexIsStale(paths: WikiPaths, pages = listPages(paths)): boolean {
  const prev = fs.existsSync(paths.index) ? fs.readFileSync(paths.index, 'utf8') : undefined;
  return prev !== renderIndexFile(paths, pages);
}
